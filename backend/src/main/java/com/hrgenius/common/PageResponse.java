package com.hrgenius.common;

import java.util.List;

import org.springframework.data.domain.Page;

/**
 * Stable pagination envelope decoupled from Spring's PageImpl JSON
 * (which changes shape between Spring versions).
 */
public record PageResponse<T>(
        List<T> content,
        int page,
        int size,
        long totalElements,
        int totalPages,
        boolean first,
        boolean last
) {
    public static <T> PageResponse<T> of(Page<T> page) {
        return new PageResponse<>(
                page.getContent(),
                page.getNumber(),
                page.getSize(),
                page.getTotalElements(),
                page.getTotalPages(),
                page.isFirst(),
                page.isLast());
    }
}
