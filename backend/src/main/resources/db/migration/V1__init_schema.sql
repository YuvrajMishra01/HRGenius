-- =====================================================================
-- HRGenius — initial schema (Oracle syntax; also runs on H2 MODE=Oracle)
-- All tables, PKs, unique keys, check constraints. FKs and indexes are
-- added at the end (allows the DEPARTMENTS <-> EMPLOYEES circular ref).
-- Money columns are NUMBER(12,2) and are mapped to BigDecimal in Java.
-- =====================================================================

-- --------------------------------------------------------------- USERS
CREATE TABLE USERS (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL         VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    FULL_NAME     VARCHAR2(150) NOT NULL,
    ROLE          VARCHAR2(20)  NOT NULL,
    ENABLED       NUMBER(1)     DEFAULT 1 NOT NULL,
    CREATED_AT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'HR', 'MANAGER', 'EMPLOYEE')),
    CONSTRAINT CK_USERS_ENABLED CHECK (ENABLED IN (0, 1))
);

-- ----------------------------------------------------------- EMPLOYEES
CREATE TABLE EMPLOYEES (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_CODE   VARCHAR2(20)  NOT NULL,
    FIRST_NAME      VARCHAR2(60)  NOT NULL,
    LAST_NAME       VARCHAR2(60)  NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL,
    PHONE           VARCHAR2(20),
    DATE_OF_BIRTH   DATE,
    GENDER          VARCHAR2(10),
    ADDRESS         VARCHAR2(255),
    JOINING_DATE    DATE          NOT NULL,
    EMPLOYMENT_TYPE VARCHAR2(20)  NOT NULL,
    STATUS          VARCHAR2(20)  NOT NULL,
    DEPARTMENT_ID   NUMBER(19),
    DESIGNATION_ID  NUMBER(19),
    MANAGER_ID      NUMBER(19),
    CREATED_AT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_EMP_CODE UNIQUE (EMPLOYEE_CODE),
    CONSTRAINT UK_EMP_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_EMP_TYPE CHECK (EMPLOYMENT_TYPE IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN')),
    CONSTRAINT CK_EMP_STATUS CHECK (STATUS IN ('ACTIVE', 'ON_LEAVE', 'RESIGNED', 'TERMINATED')),
    CONSTRAINT CK_EMP_GENDER CHECK (GENDER IS NULL OR GENDER IN ('MALE', 'FEMALE', 'OTHER'))
);

-- --------------------------------------------------------- DEPARTMENTS
CREATE TABLE DEPARTMENTS (
    ID          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(255),
    MANAGER_ID  NUMBER(19),
    CONSTRAINT UK_DEPT_NAME UNIQUE (NAME)
);

-- -------------------------------------------------------- DESIGNATIONS
CREATE TABLE DESIGNATIONS (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE         VARCHAR2(100) NOT NULL,
    DESCRIPTION   VARCHAR2(255),
    DEPARTMENT_ID NUMBER(19),
    CONSTRAINT UK_DESG_TITLE_DEPT UNIQUE (TITLE, DEPARTMENT_ID)
);

-- ---------------------------------------------------------------- JOBS
CREATE TABLE JOBS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE           VARCHAR2(150) NOT NULL,
    DESCRIPTION     CLOB,
    DEPARTMENT_ID   NUMBER(19),
    LOCATION        VARCHAR2(100),
    EMPLOYMENT_TYPE VARCHAR2(20),
    SALARY_RANGE    VARCHAR2(60),
    STATUS          VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    POSTED_DATE     DATE,
    CLOSING_DATE    DATE,
    CONSTRAINT CK_JOB_STATUS CHECK (STATUS IN ('DRAFT', 'OPEN', 'CLOSED')),
    CONSTRAINT CK_JOB_TYPE CHECK (EMPLOYMENT_TYPE IS NULL OR
        EMPLOYMENT_TYPE IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN'))
);

-- ----------------------------------------------------------- CANDIDATES
CREATE TABLE CANDIDATES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME             VARCHAR2(150) NOT NULL,
    EMAIL            VARCHAR2(150) NOT NULL,
    PHONE            VARCHAR2(20),
    RESUME_PATH      VARCHAR2(255),
    SKILLS           VARCHAR2(500),
    EXPERIENCE_YEARS NUMBER(4,1),
    STATUS           VARCHAR2(20) DEFAULT 'NEW' NOT NULL,
    CREATED_AT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_CAND_STATUS CHECK (STATUS IN
        ('NEW', 'SCREENING', 'SHORTLISTED', 'INTERVIEWED', 'SELECTED', 'REJECTED', 'HIRED'))
);

-- ----------------------------------------------------- JOB_APPLICATIONS
CREATE TABLE JOB_APPLICATIONS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CANDIDATE_ID     NUMBER(19) NOT NULL,
    JOB_ID           NUMBER(19) NOT NULL,
    APPLICATION_DATE DATE       DEFAULT CURRENT_DATE NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'APPLIED' NOT NULL,
    REMARKS          VARCHAR2(500),
    CONSTRAINT UK_APP_CAND_JOB UNIQUE (CANDIDATE_ID, JOB_ID),
    CONSTRAINT CK_APP_STATUS CHECK (STATUS IN
        ('APPLIED', 'SCREENING', 'SHORTLISTED', 'INTERVIEW', 'SELECTED', 'REJECTED'))
);

-- ----------------------------------------------------------- INTERVIEWS
-- Note: MODE is a reserved word on both Oracle and H2, hence INTERVIEW_MODE.
CREATE TABLE INTERVIEWS (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER(19)    NOT NULL,
    INTERVIEWER_ID NUMBER(19),
    INTERVIEW_DATE TIMESTAMP     NOT NULL,
    INTERVIEW_MODE VARCHAR2(20)  NOT NULL,
    STATUS         VARCHAR2(20)  DEFAULT 'SCHEDULED' NOT NULL,
    FEEDBACK       VARCHAR2(1000),
    RESULT         VARCHAR2(20),
    CONSTRAINT CK_INT_MODE CHECK (INTERVIEW_MODE IN ('ONSITE', 'ONLINE', 'PHONE')),
    CONSTRAINT CK_INT_STATUS CHECK (STATUS IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT CK_INT_RESULT CHECK (RESULT IS NULL OR RESULT IN ('PASS', 'FAIL', 'ON_HOLD'))
);

-- ---------------------------------------------------------- ONBOARDINGS
CREATE TABLE ONBOARDINGS (
    ID                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID           NUMBER(19) NOT NULL,
    JOINING_DATE          DATE,
    STATUS                VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    COMPLETION_PERCENTAGE NUMBER(5,2) DEFAULT 0 NOT NULL,
    CHECKLIST             CLOB,
    CONSTRAINT UK_ONB_EMPLOYEE UNIQUE (EMPLOYEE_ID),
    CONSTRAINT CK_ONB_STATUS CHECK (STATUS IN ('PENDING', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT CK_ONB_PCT CHECK (COMPLETION_PERCENTAGE BETWEEN 0 AND 100)
);

-- ----------------------------------------------------------- ATTENDANCE
CREATE TABLE ATTENDANCE (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID     NUMBER(19) NOT NULL,
    ATTENDANCE_DATE DATE       NOT NULL,
    CHECK_IN        TIMESTAMP,
    CHECK_OUT       TIMESTAMP,
    STATUS          VARCHAR2(20) NOT NULL,
    WORKING_HOURS   NUMBER(4,2),
    CONSTRAINT UK_ATT_EMP_DATE UNIQUE (EMPLOYEE_ID, ATTENDANCE_DATE),
    CONSTRAINT CK_ATT_STATUS CHECK (STATUS IN
        ('PRESENT', 'ABSENT', 'HALF_DAY', 'LEAVE', 'HOLIDAY'))
);

-- ---------------------------------------------------------- LEAVE_TYPES
CREATE TABLE LEAVE_TYPES (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME         VARCHAR2(50) NOT NULL,
    DESCRIPTION  VARCHAR2(255),
    YEARLY_LIMIT NUMBER(3)    NOT NULL,
    CONSTRAINT UK_LTYPE_NAME UNIQUE (NAME)
);

-- ------------------------------------------------------- LEAVE_REQUESTS
CREATE TABLE LEAVE_REQUESTS (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID   NUMBER(19) NOT NULL,
    LEAVE_TYPE_ID NUMBER(19) NOT NULL,
    START_DATE    DATE       NOT NULL,
    END_DATE      DATE       NOT NULL,
    REASON        VARCHAR2(500),
    STATUS        VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    APPROVED_BY   NUMBER(19),
    CREATED_AT    TIMESTAMP  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_LR_DATES CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_LR_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

-- ------------------------------------------------------------- PAYROLLS
-- PAY_MONTH / PAY_YEAR avoid the reserved words MONTH and YEAR.
CREATE TABLE PAYROLLS (
    ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID  NUMBER(19)    NOT NULL,
    PAY_MONTH    NUMBER(2)     NOT NULL,
    PAY_YEAR     NUMBER(4)     NOT NULL,
    BASIC_SALARY NUMBER(12,2)  NOT NULL,
    ALLOWANCES   NUMBER(12,2)  NOT NULL,
    DEDUCTIONS   NUMBER(12,2)  NOT NULL,
    TAX          NUMBER(12,2)  NOT NULL,
    NET_SALARY   NUMBER(12,2)  NOT NULL,
    STATUS       VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
    CONSTRAINT UK_PAY_EMP_PERIOD UNIQUE (EMPLOYEE_ID, PAY_YEAR, PAY_MONTH),
    CONSTRAINT CK_PAY_MONTH CHECK (PAY_MONTH BETWEEN 1 AND 12),
    CONSTRAINT CK_PAY_STATUS CHECK (STATUS IN ('DRAFT', 'PROCESSED', 'PAID'))
);

-- ------------------------------------------------- PERFORMANCE_REVIEWS
CREATE TABLE PERFORMANCE_REVIEWS (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID   NUMBER(19)    NOT NULL,
    REVIEWER_ID   NUMBER(19)    NOT NULL,
    REVIEW_PERIOD VARCHAR2(20),
    RATING        NUMBER(1),
    STRENGTHS     VARCHAR2(1000),
    WEAKNESSES    VARCHAR2(1000),
    GOALS         VARCHAR2(1000),
    COMMENTS      VARCHAR2(1000),
    STATUS        VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
    CONSTRAINT CK_PR_RATING CHECK (RATING IS NULL OR RATING BETWEEN 1 AND 5),
    CONSTRAINT CK_PR_STATUS CHECK (STATUS IN ('DRAFT', 'SUBMITTED', 'ACKNOWLEDGED'))
);

-- ------------------------------------------------------------ DOCUMENTS
CREATE TABLE DOCUMENTS (
    ID            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID   NUMBER(19)    NOT NULL,
    DOCUMENT_TYPE VARCHAR2(30)  NOT NULL,
    FILE_NAME     VARCHAR2(255) NOT NULL,
    FILE_PATH     VARCHAR2(500) NOT NULL,
    FILE_SIZE     NUMBER(12),
    UPLOADED_AT   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_DOC_TYPE CHECK (DOCUMENT_TYPE IN
        ('RESUME', 'OFFER_LETTER', 'ID_PROOF', 'CERTIFICATE', 'EXPERIENCE_LETTER', 'OTHER'))
);

-- --------------------------------------------------------- NOTIFICATIONS
CREATE TABLE NOTIFICATIONS (
    ID         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID    NUMBER(19)    NOT NULL,
    TITLE      VARCHAR2(150) NOT NULL,
    MESSAGE    VARCHAR2(1000),
    TYPE       VARCHAR2(30),
    READ_FLAG  NUMBER(1)     DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_NOTIF_READ CHECK (READ_FLAG IN (0, 1))
);

-- =====================================================================
-- Foreign keys (after all tables exist; enables the circular
-- DEPARTMENTS.MANAGER_ID <-> EMPLOYEES relationship)
-- =====================================================================
ALTER TABLE EMPLOYEES ADD CONSTRAINT FK_EMP_DEPT
    FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID);
ALTER TABLE EMPLOYEES ADD CONSTRAINT FK_EMP_DESG
    FOREIGN KEY (DESIGNATION_ID) REFERENCES DESIGNATIONS (ID);
ALTER TABLE EMPLOYEES ADD CONSTRAINT FK_EMP_MANAGER
    FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE DEPARTMENTS ADD CONSTRAINT FK_DEPT_MANAGER
    FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE DESIGNATIONS ADD CONSTRAINT FK_DESG_DEPT
    FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID);
ALTER TABLE JOBS ADD CONSTRAINT FK_JOB_DEPT
    FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID);
ALTER TABLE JOB_APPLICATIONS ADD CONSTRAINT FK_APP_CAND
    FOREIGN KEY (CANDIDATE_ID) REFERENCES CANDIDATES (ID);
ALTER TABLE JOB_APPLICATIONS ADD CONSTRAINT FK_APP_JOB
    FOREIGN KEY (JOB_ID) REFERENCES JOBS (ID);
ALTER TABLE INTERVIEWS ADD CONSTRAINT FK_INT_APP
    FOREIGN KEY (APPLICATION_ID) REFERENCES JOB_APPLICATIONS (ID);
ALTER TABLE INTERVIEWS ADD CONSTRAINT FK_INT_INTERVIEWER
    FOREIGN KEY (INTERVIEWER_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE ONBOARDINGS ADD CONSTRAINT FK_ONB_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE ATTENDANCE ADD CONSTRAINT FK_ATT_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE LEAVE_REQUESTS ADD CONSTRAINT FK_LR_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE LEAVE_REQUESTS ADD CONSTRAINT FK_LR_TYPE
    FOREIGN KEY (LEAVE_TYPE_ID) REFERENCES LEAVE_TYPES (ID);
ALTER TABLE LEAVE_REQUESTS ADD CONSTRAINT FK_LR_APPROVER
    FOREIGN KEY (APPROVED_BY) REFERENCES USERS (ID);
ALTER TABLE PAYROLLS ADD CONSTRAINT FK_PAY_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE PERFORMANCE_REVIEWS ADD CONSTRAINT FK_PR_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE PERFORMANCE_REVIEWS ADD CONSTRAINT FK_PR_REVIEWER
    FOREIGN KEY (REVIEWER_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE DOCUMENTS ADD CONSTRAINT FK_DOC_EMP
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES (ID);
ALTER TABLE NOTIFICATIONS ADD CONSTRAINT FK_NOTIF_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID);

-- =====================================================================
-- Indexes for frequent lookups
-- =====================================================================
CREATE INDEX IX_EMP_DEPT       ON EMPLOYEES (DEPARTMENT_ID);
CREATE INDEX IX_EMP_STATUS     ON EMPLOYEES (STATUS);
CREATE INDEX IX_APPS_JOB       ON JOB_APPLICATIONS (JOB_ID);
CREATE INDEX IX_APPS_STATUS    ON JOB_APPLICATIONS (STATUS);
CREATE INDEX IX_INT_APPL       ON INTERVIEWS (APPLICATION_ID);
CREATE INDEX IX_LR_EMP         ON LEAVE_REQUESTS (EMPLOYEE_ID);
CREATE INDEX IX_LR_STATUS      ON LEAVE_REQUESTS (STATUS);
CREATE INDEX IX_PAY_EMP_PERIOD ON PAYROLLS (EMPLOYEE_ID, PAY_YEAR, PAY_MONTH);
CREATE INDEX IX_NOTIF_USER_READ ON NOTIFICATIONS (USER_ID, READ_FLAG);
